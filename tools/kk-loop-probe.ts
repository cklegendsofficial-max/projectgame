import { chromium } from "playwright-core";

const browser = await chromium.launch({ channel: "msedge", headless: true, args: ["--enable-gpu", "--ignore-gpu-blocklist", "--use-angle=d3d11"] });
const page = await browser.newPage({ viewport: { width: 1280, height: 720 } });
const errs: string[] = [];
page.on("pageerror", (e) => errs.push(e.message));
page.on("console", (m) => m.type() === "error" && errs.push(m.text()));
await page.addInitScript(() => localStorage.clear());
await page.goto("http://localhost:5174/");
await page.waitForFunction(() => !document.getElementById("loading"), null, { timeout: 60000 });
const ev = (fn: string) => page.evaluate(`(() => { const g = window.game; ${fn} })()`);
const log = async (tag: string) => console.log(tag, JSON.stringify(await ev(`return { q: g.s.quest, res: Object.fromEntries(Object.entries(g.s.res).map(([k,v]) => [k, Math.round(v)])), hero: g.s.hero.army, gar: g.s.garrison, lv: g.s.hero.lv, marches: g.s.marches.map(m => m.phase), bandits: g.s.bandits.length };`)));

await log("start");
await ev(`g.goTo({kind:"point", x: g.s.hero.x + 60, y: g.s.hero.y + 40});`);
await page.waitForTimeout(1500);
await ev(`const v = g.nearest(g.s.villages); const i = g.s.villages.indexOf(v); g.s.hero.x = v.x; g.s.hero.y = v.y; g.recruit(i, 5);`);
await page.waitForTimeout(500);
await log("recruited");
await ev(`g.s.res.gold += 2000; g.s.res.food += 2000; g.s.res.wood += 2000; g.s.res.stone += 2000;`);
const b = await page.evaluate(`(() => { const g = window.game; const b = g.s.bandits[0] ?? null; if (!b) return null; g.s.hero.x = b.x + 10; g.s.hero.y = b.y; g.s.hero.army = {spear: 30, archer: 10, horse: 0}; g.goTo({kind:"bandit", i: b.id}); return b.id; })()`);
console.log("bandit target", b);
await page.waitForTimeout(1500);
await page.locator(".battle .result .btn").click({ timeout: 15000 });
await log("fought");
await ev(`g.upgrade("ciftlik");`);
await page.waitForTimeout(13500);
await log("built");
await ev(`g.train("spear", 10);`);
await page.waitForTimeout(500);
await ev(`g.s.queue.forEach(o => o.done = Date.now());`);
await page.waitForTimeout(800);
await log("trained");
await ev(`const n = g.nearest(g.s.nodes); g.sendMarch(g.s.nodes.indexOf(n), {spear: 10, archer: 0, horse: 0});`);
await page.waitForTimeout(1000);
await log("marched");
await ev(`const m = g.s.marches[0]; if (m) { m.x = m.path[m.path.length-2]; m.y = m.path[m.path.length-1]; m.pathI = m.path.length; }`);
await page.waitForTimeout(600);
await ev(`const m = g.s.marches[0]; if (m) m.until = Date.now();`);
await page.waitForTimeout(600);
await ev(`const m = g.s.marches[0]; if (m) { m.x = m.path[m.path.length-2]; m.y = m.path[m.path.length-1]; m.pathI = m.path.length; }`);
await page.waitForTimeout(800);
await log("returned");
await page.reload();
await page.waitForFunction(() => !document.getElementById("loading"), null, { timeout: 60000 });
await log("reloaded");
console.log("errors:", errs);
await browser.close();
