import { chromium } from "playwright-core";

const mode = process.argv[2] ?? "desk";
const browser = await chromium.launch({ channel: "msedge", headless: true, args: ["--enable-gpu", "--ignore-gpu-blocklist", "--use-angle=d3d11"] });
const vp = mode === "mob" ? { width: 390, height: 844 } : { width: 1280, height: 720 };
const page = await browser.newPage({ viewport: vp, deviceScaleFactor: mode === "mob" ? 2 : 1, hasTouch: mode === "mob" });
const errs: string[] = [];
page.on("pageerror", (e) => errs.push(e.message));
page.on("console", (m) => m.type() === "error" && errs.push(m.text()));
await page.goto("http://localhost:5174/");
await page.evaluate(() => localStorage.clear());
await page.reload();
await page.waitForFunction(() => !document.getElementById("loading"), null, { timeout: 60000 });
const ev = <T = unknown>(fn: string) => page.evaluate(`(() => { const g = window.game; ${fn} })()`) as Promise<T>;
console.log("origins:", await page.locator(".ocard").allInnerTexts());
await page.locator(`.ocard[data-o="tuccar"]`).click();
console.log("detail:", (await page.locator(".odet").innerText()).slice(0, 80).replace(/\n/g, " "));
await page.screenshot({ path: `playtest/origin-${mode}.png` });
const before = await ev(`return [g.s.res.gold, g.s.hero.skills.ticaret, g.sellFactor()];`);
await page.locator(".cname .btn").click();
await page.waitForTimeout(300);
console.log("intro:", (await page.locator(".battle .bbox.story").innerText()).slice(0, 90).replace(/\n/g, " "));
console.log("before:", before, "after:", await ev(`return [g.s.origin, g.s.res.gold, g.s.hero.skills.ticaret, g.s.hero.stats.kar, g.sellFactor(), g.s.bond];`));
console.log("errors:", errs);
await browser.close();
