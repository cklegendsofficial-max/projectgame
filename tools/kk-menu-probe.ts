import { chromium } from "playwright-core";

const mode = process.argv[2] ?? "desk";
const out = `playtest/menu-${mode}`;
const browser = await chromium.launch({ channel: "msedge", headless: true, args: ["--enable-gpu", "--ignore-gpu-blocklist", "--use-angle=d3d11"] });
const vp = mode === "mob" ? { width: 390, height: 844 } : { width: 1280, height: 720 };
const page = await browser.newPage({ viewport: vp, deviceScaleFactor: mode === "mob" ? 2 : 1, hasTouch: mode === "mob" });
const errs: string[] = [];
page.on("pageerror", (e) => errs.push(e.message));
page.on("console", (m) => m.type() === "error" && errs.push(m.text()));
await page.goto("http://localhost:5174/?title");
await page.evaluate(() => localStorage.clear());
await page.reload();
await page.waitForFunction(() => !document.getElementById("loading"), null, { timeout: 60000 });
const ev = <T = unknown>(fn: string) => page.evaluate(`(() => { const g = window.game; ${fn} })()`) as Promise<T>;
await page.waitForTimeout(1500);
console.log("title:", await page.locator(".kkmenu.title").count(), "btns:", await page.locator(".kkmenu .mbtn b").allInnerTexts(), "csel:", await page.locator(".csel").count());
const t0 = await ev<number>(`return g.s.time;`);
await page.waitForTimeout(1500);
console.log("paused:", (await ev<number>(`return g.s.time;`)) === t0);
await page.screenshot({ path: `${out}-1.png` });
await page.locator(".kkmenu .mbtn.go").click();
await page.waitForTimeout(700);
console.log("after start: menu", await page.locator(".kkmenu").count(), "csel", await page.locator(".csel").count());
await page.locator(`.ccard[data-c="kam"]`).click();
await page.locator(".cname .btn").click();
await page.waitForTimeout(400);
for (let k = 0; k < 6 && (await page.locator(".battle .bbox.story .btn").count()); k++) {
  await page.locator(".battle .bbox.story .btn").first().click();
  await page.waitForTimeout(250);
}
await page.keyboard.press("Escape");
await page.waitForTimeout(300);
console.log("esc -> pause menu:", await page.locator(".kkmenu:not(.title)").count(), await page.locator(".kkmenu .mbtn b").allInnerTexts());
await page.screenshot({ path: `${out}-2.png` });
await page.keyboard.press("h");
console.log("h ignored in menu:", await ev(`return g.hud.panelOpen();`), await page.locator(".panel:not(.hidden)").count());
await page.locator(".kkmenu .mbtn", { hasText: "Ayarlar" }).click();
await page.waitForTimeout(300);
console.log("settings: menu", await page.locator(".kkmenu").count(), "tab", await page.locator(".panel .tab.on").innerText());
await page.keyboard.press("Escape");
await page.keyboard.press("Escape");
await page.waitForTimeout(200);
console.log("esc esc -> menu:", await page.locator(".kkmenu").count());
await page.keyboard.press("Escape");
await page.waitForTimeout(200);
console.log("esc -> closed:", await page.locator(".kkmenu").count());
const t1 = await ev<number>(`return g.s.time;`);
await page.waitForTimeout(800);
console.log("running:", (await ev<number>(`return g.s.time;`)) > t1);
await ev(`g.saveNow();`);
await page.reload();
await page.waitForFunction(() => !document.getElementById("loading"), null, { timeout: 60000 });
await page.waitForTimeout(800);
console.log("reload title btn:", await page.locator(".kkmenu .mbtn.go").innerText());
await page.screenshot({ path: `${out}-3.png` });
console.log("errors:", errs);
await browser.close();
